"""Build the product dataset (BUILD_GUIDE section 7.5) from the parsed EPC properties.

  1. stratified sample of `product_sample_size` in-scope properties (local authority x property type)
  2. synthetic customers + the single customer-grouped train/val/test split
  3. hidden household factors (sim_hidden.parquet; never model features)
  4. calibration of the physics model to NEED medians, fitted on TRAIN homes only
  5. synthetic monthly meter readings with documented missingness
  6. simulator labels: K packages per home (labels/energy_scenarios.parquet) and the
     improvement-potential reference (labels/improvement_potential_ref.parquet)
  7. score helpers from TRAIN only: intensity bounds (P5/P95) and peer percentiles
Everything is seeded from config/data_pipeline.yaml.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd
import yaml

from data_pipeline import calibrate, synth_energy
from data_pipeline import physics as ph
from data_pipeline import simulator as sim
from data_pipeline.kernels import feasible_frame as feasible_set
from data_pipeline.make_splits import assign_customers, make_splits

ROOT = Path(__file__).resolve().parents[1]
INTERIM = ROOT / "data" / "interim"
PROCESSED = ROOT / "data" / "processed"
LABELS = PROCESSED / "labels"
GENERATED = ROOT / "config" / "generated"
REPORTS = ROOT / "reports"
CFG = yaml.safe_load((ROOT / "config" / "data_pipeline.yaml").read_text())
SEED = CFG["seed"]
K_PACKAGES = 8

FEATURES = [
    "property_type",
    "age_band",
    "floor_area_m2",
    "habitable_rooms",
    "bedrooms",
    "region",
    "roof_type",
    "roof_insulation",
    "wall_type",
    "wall_insulation",
    "glazing",
    "heating_system",
    "main_fuel",
    "renewables",
    "smart_controls",
    "gas_connected",
    "listed_or_conservation",
    "outdoor_space",
    "energy_rating",
    "sap_score",
]
FLOOR_AREA_BANDS = [0, 50, 90, 130, 200, np.inf]
FLOOR_AREA_LABELS = ["<50", "50-90", "90-130", "130-200", ">200"]


def all_property_splits(rng: np.random.Generator) -> pd.DataFrame:
    """Customers + split for EVERY EPC property (rating/recommender/value models use them all)."""
    certs = pd.read_parquet(PROCESSED / "epc_certificates_model.parquet", columns=["property_id", "region"])
    allp = certs.drop_duplicates("property_id", keep="last").sort_values("property_id").reset_index(drop=True)
    allp["customer_id"] = assign_customers(allp, rng).values
    return make_splits(allp, SEED)


def sample_properties(rng: np.random.Generator) -> pd.DataFrame:
    p = pd.read_parquet(INTERIM / "properties_latest.parquet")
    n = CFG["product_sample_size"]
    strata = p["LOCAL_AUTHORITY"].astype(str) + "|" + p["property_type"].astype(str)
    frac = n / len(p)
    idx = (
        p.groupby(strata, group_keys=False)
        .apply(lambda g: g.sample(n=max(1, int(round(len(g) * frac))), random_state=SEED))
        .index
    )
    s = p.loc[idx].copy()
    if len(s) > n:
        s = s.sample(n=n, random_state=SEED)
    s = s.rename(columns={"LOCAL_AUTHORITY": "local_authority_code", "lodgement_date": "epc_lodgement_date"})
    s["data_source"] = "epc_real"
    return s.sort_values("property_id").reset_index(drop=True)


def intensity_and_peers(props: pd.DataFrame, true_annual: pd.DataFrame, train: pd.Series) -> None:
    t = props[["property_id", "property_type", "floor_area_m2"]].merge(true_annual, on="property_id")
    t["intensity"] = (t["true_annual_electricity_kwh"] + t["true_annual_gas_kwh"]) / t["floor_area_m2"]
    t["floor_area_band"] = pd.cut(t["floor_area_m2"], FLOOR_AREA_BANDS, labels=FLOOR_AREA_LABELS).astype(str)
    tr = t[t["property_id"].isin(train)]
    bounds = {
        "i_best": float(5 * round(tr["intensity"].quantile(0.05) / 5)),
        "i_worst": float(5 * round(tr["intensity"].quantile(0.95) / 5)),
        "basis": "P5/P95 of annual purchased kWh (grid import + gas) per m2, train split only",
        "n_train_homes": int(len(tr)),
    }
    GENERATED.mkdir(parents=True, exist_ok=True)
    (GENERATED / "intensity_bounds.yaml").write_text(
        "# Generated by data_pipeline/build_dataset.py, do not edit by hand.\n"
        + yaml.safe_dump(bounds, sort_keys=False)
    )
    peers = (
        tr.groupby(["property_type", "floor_area_band"])["intensity"]
        .quantile([0.10, 0.50, 0.75, 0.90])
        .unstack()
        .reset_index()
    )
    peers.columns = ["property_type", "floor_area_band", "p10", "p50", "p75", "p90"]
    peers["n"] = tr.groupby(["property_type", "floor_area_band"]).size().values
    peers.to_parquet(GENERATED / "peer_percentiles.parquet", index=False)
    print("intensity bounds:", bounds)


def simulate_labels(props, hidden, cal_sh, cal_el, rng) -> pd.DataFrame:
    feas = feasible_set(props)
    packages = sim.sample_packages(feas, K_PACKAGES, rng)
    base = ph.delivered(props, hidden, ph.end_uses(props, hidden, cal_sh, cal_el))
    rows = [(i, pk) for i, pks in enumerate(packages) for pk in pks]
    by_pkg: dict[frozenset, list[int]] = {}
    for i, pk in rows:
        by_pkg.setdefault(pk, []).append(i)
    out = []
    for pk, idx in by_pkg.items():
        idx = np.array(idx)
        a = sim.simulate(
            props.iloc[idx].reset_index(drop=True),
            hidden.iloc[idx].reset_index(drop=True),
            cal_sh.iloc[idx].reset_index(drop=True),
            cal_el.iloc[idx].reset_index(drop=True),
            pk,
        )
        d = pd.DataFrame(
            {
                "property_id": props["property_id"].to_numpy()[idx],
                "package": "+".join(sorted(pk)),
                "elec_before": base["electricity_kwh"].to_numpy()[idx],
                "gas_before": base["gas_kwh"].to_numpy()[idx],
                "elec_after": a["electricity_kwh"].to_numpy(),
                "gas_after": a["gas_kwh"].to_numpy(),
                "pv_self_consumed_after": a["pv_self_consumed_kwh"].to_numpy(),
            }
        )
        for r in ph.RETROFITS:
            d[f"r_{r}"] = r in pk
        out.append(d)
    lab = pd.concat(out, ignore_index=True).sort_values(["property_id", "package"]).reset_index(drop=True)
    lab["package_id"] = lab.groupby("property_id").cumcount()
    return lab


def main() -> None:
    rng = np.random.default_rng(SEED)
    splits_all = all_property_splits(rng)
    props = sample_properties(rng)
    props = props.merge(splits_all[["property_id", "customer_id"]], on="property_id", how="left")
    assert props["customer_id"].notna().all()
    splits_all["in_product_sample"] = splits_all["property_id"].isin(props["property_id"])
    splits = splits_all[splits_all["in_product_sample"]]
    train_ids = splits.loc[splits["split"] == "train", "property_id"]
    print(
        f"all properties: {len(splits_all):,} ({splits_all.customer_id.nunique():,} customers) "
        f"{splits_all['split'].value_counts(normalize=True).round(3).to_dict()}"
    )
    print(f"product sample: {len(props):,}; {splits['split'].value_counts().to_dict()}")

    hidden = ph.draw_hidden(props, rng)
    is_train = props["property_id"].isin(train_ids).to_numpy()
    cal_sh_tr, cal_el_tr, rep_gas, rep_el, factors = calibrate.calibrate(
        props[is_train].reset_index(drop=True), hidden[is_train].reset_index(drop=True)
    )
    # apply the train-fitted cell factors to every home
    gas_cell = (
        props["property_type"].map(calibrate.PTYPE_GROUP)
        + "|"
        + props["age_band"].map(calibrate.AGE_GROUP_OURS)
    )
    el_cell = (
        props["property_type"].map(calibrate.PTYPE_GROUP) + "|" + calibrate.beds_group(props["bedrooms"])
    )
    f_sh = factors[factors["kind"] == "space_heat"]["factor"]
    f_el = factors[factors["kind"] == "appliances"]["factor"]
    f_band = factors[factors["kind"] == "prebound_band"]["factor"]
    cal_sh = gas_cell.map(f_sh).fillna(f_sh.median()) * props["energy_rating"].map(f_band).fillna(1.0)
    cal_el = el_cell.map(f_el).fillna(f_el.median())

    eu = ph.end_uses(props, hidden, cal_sh, cal_el)
    fuel = ph.delivered(props, hidden, eu)
    monthly, meta = synth_energy.monthly_readings(props, eu, fuel, CFG["energy_year_end_month"], rng)

    LABELS.mkdir(parents=True, exist_ok=True)
    REPORTS.mkdir(exist_ok=True)
    rep_gas.round(1).to_csv(REPORTS / "calibration_gas.csv")
    rep_el.round(1).to_csv(REPORTS / "calibration_electricity.csv")
    rep_gas.attrs["band"].round(3).to_csv(REPORTS / "calibration_gas_by_band.csv")
    factors.to_csv(REPORTS / "calibration_factors.csv")

    out = props.merge(splits[["property_id", "customer_id"]], on=["property_id", "customer_id"])
    out = out.merge(
        meta[["property_id", "annual_electricity_kwh", "annual_gas_kwh", "missingness_pattern"]],
        on="property_id",
    )
    out[
        [
            "property_id",
            "customer_id",
            "local_authority_code",
            "epc_lodgement_date",
            "data_source",
            "annual_electricity_kwh",
            "annual_gas_kwh",
            "missingness_pattern",
        ]
        + FEATURES
    ].to_parquet(INTERIM / "properties_pre_value.parquet", index=False)
    monthly.to_parquet(PROCESSED / "energy_monthly.parquet", index=False)
    hidden.assign(cal_sh=cal_sh.values, cal_el=cal_el.values).to_parquet(
        PROCESSED / "sim_hidden.parquet", index=False
    )
    splits_all.to_parquet(PROCESSED / "splits.parquet", index=False)
    meta[["property_id", "true_annual_electricity_kwh", "true_annual_gas_kwh"]].to_parquet(
        LABELS / "true_annual_energy.parquet", index=False
    )

    intensity_and_peers(props, meta, train_ids)

    lab = simulate_labels(props, hidden, cal_sh, cal_el, rng)
    lab.to_parquet(LABELS / "energy_scenarios.parquet", index=False)
    feas = feasible_set(props)
    full = feas.apply(lambda r: "+".join(sorted(feas.columns[r.to_numpy()])), axis=1)
    ip = lab.merge(
        pd.DataFrame({"property_id": props["property_id"], "package": full}), on=["property_id", "package"]
    )
    base_total = ip["elec_before"] + ip["gas_before"]
    ip["ip_ref_pct"] = np.where(
        base_total > 0, 100 * (base_total - ip["elec_after"] - ip["gas_after"]) / base_total, np.nan
    )
    ip = ip.merge(splits[["property_id", "split"]], on="property_id")
    ip["rank_ref"] = ip.groupby("split")["ip_ref_pct"].rank(ascending=False, method="min").astype("Int64")
    ip[["property_id", "package", "ip_ref_pct", "rank_ref", "split"]].to_parquet(
        LABELS / "improvement_potential_ref.parquet", index=False
    )
    print(
        f"energy scenarios: {len(lab):,} rows; improvement potential median "
        f"{ip['ip_ref_pct'].median():.1f}% "
        f"(IQR {ip['ip_ref_pct'].quantile(0.25):.1f}-{ip['ip_ref_pct'].quantile(0.75):.1f})"
    )


if __name__ == "__main__":
    main()
