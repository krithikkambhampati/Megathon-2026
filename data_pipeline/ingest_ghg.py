"""Extract the electricity and natural-gas emission factors from the DESNZ 2026 flat file
and write config/emission_factors.yaml. Values are looked up by their DESNZ factor ID so
the config can never silently pick a different row.
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "data" / "raw" / "ghg" / "ghg-conversion-factors-2026-flat-format-revised.xlsx"
OUT = ROOT / "config" / "emission_factors.yaml"
DOWNLOADS = ROOT / "data" / "raw" / "DOWNLOADS.json"
YEAR = 2026

IDS = {
    "electricity": "7_400_4000_5_1",  # Scope 2, UK electricity, generated, kWh, kg CO2e
    "electricity_td": "13_402_4000_5_1",  # Scope 3, T&D losses, UK electricity, kWh, kg CO2e
    "gas": "1_100_1004_6_1",  # Scope 1, natural gas, kWh (Gross CV), kg CO2e
    "gas_wtt": "11_100_1004_6_1",  # Scope 3, well-to-tank natural gas, kWh (Gross CV)
}


def main() -> None:
    t = pd.read_excel(SRC, sheet_name="Factors by Category", header=5)
    t = t.set_index("ID")
    val = {k: float(t.loc[i, f"GHG Conversion Factor {YEAR}"]) for k, i in IDS.items()}
    for k, i in IDS.items():
        assert t.loc[i, "GHG/Unit"] == "kg CO2e", (k, t.loc[i, "GHG/Unit"])
    assert t.loc[IDS["gas"], "UOM"] == "kWh (Gross CV)"
    url = json.loads(DOWNLOADS.read_text())["ghg/" + SRC.name]["url"]
    src = f"DESNZ Greenhouse gas reporting: conversion factors {YEAR}, flat file v1.2 ({url})"

    doc = [
        {
            "fuel": "electricity",
            "kg_co2e_per_kwh": val["electricity"],
            "unit": "kg CO2e per kWh of grid electricity imported",
            "scope": "Scope 2, UK electricity generated (location-based); excludes T&D losses",
            "td_losses_kg_co2e_per_kwh": val["electricity_td"],
            "desnz_id": IDS["electricity"],
            "source": src,
            "year": YEAR,
        },
        {
            "fuel": "gas",
            "kg_co2e_per_kwh": val["gas"],
            "unit": "kg CO2e per kWh of mains gas (gross calorific value, as billed)",
            "scope": "Scope 1 combustion of natural gas; excludes well-to-tank",
            "wtt_kg_co2e_per_kwh": val["gas_wtt"],
            "desnz_id": IDS["gas"],
            "source": src,
            "year": YEAR,
        },
    ]
    header = (
        "# Generated by data_pipeline/ingest_ghg.py, do not edit by hand.\n"
        "# Carbon: dC_kg = dE_elec_kwh * electricity.kg_co2e_per_kwh + dE_gas_kwh * gas.kg_co2e_per_kwh\n"
        "# Gas meters bill kWh on a gross-CV basis, so the Gross CV factor is the correct match.\n"
        "# T&D and WTT factors are recorded for transparency/sensitivity;\n"
        "# the headline uses the main factor.\n"
    )
    OUT.write_text(header + yaml.safe_dump(doc, sort_keys=False))
    print(OUT.read_text())


if __name__ == "__main__":
    main()
