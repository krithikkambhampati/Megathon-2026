"""Data-quality report with validation charts -> reports/data_report.md + reports/figures/*.png.

Every chart compares our data with an independent real reference (NEED, national EPC mix, repeat EPCs)
and is followed by the same numbers as a table. Colours: reference palette slots 1 (ours) and 2 (NEED).
"""
from __future__ import annotations

from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
PROCESSED = ROOT / "data" / "processed"
REPORTS = ROOT / "reports"
FIG = REPORTS / "figures"

OURS, REF = "#2a78d6", "#eb6834"            # categorical slots 1 and 2 (validated adjacent pair)
SURFACE, INK, INK2, GRID = "#fcfcfb", "#0b0b0b", "#52514e", "#e4e3df"


def style(ax, title: str, xlabel: str = "", ylabel: str = "") -> None:
    ax.set_facecolor(SURFACE)
    ax.set_title(title, loc="left", color=INK, fontsize=11, fontweight="semibold", pad=10)
    ax.set_xlabel(xlabel, color=INK2, fontsize=9)
    ax.set_ylabel(ylabel, color=INK2, fontsize=9)
    ax.tick_params(colors=INK2, labelsize=8, length=0)
    for s in ax.spines.values():
        s.set_visible(False)
    ax.grid(axis="x" if ax.get_xlabel() and not ax.get_ylabel() else "y", color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)


def save(fig, name: str) -> str:
    FIG.mkdir(parents=True, exist_ok=True)
    fig.patch.set_facecolor(SURFACE)
    fig.tight_layout()
    fig.savefig(FIG / name, dpi=160, facecolor=SURFACE)
    plt.close(fig)
    return f"figures/{name}"


def paired_bars(ax, labels, a, b, la, lb):
    y = np.arange(len(labels))
    h = 0.38
    ax.barh(y - h / 2 - 0.01, a, height=h, color=OURS, label=la, edgecolor=SURFACE, linewidth=1)
    ax.barh(y + h / 2 + 0.01, b, height=h, color=REF, label=lb, edgecolor=SURFACE, linewidth=1)
    ax.set_yticks(y, labels)
    ax.invert_yaxis()
    ax.legend(frameon=False, fontsize=8, labelcolor=INK2, loc="lower right")


def md_table(df: pd.DataFrame) -> str:
    return df.to_markdown()


def main() -> None:
    out = ["# Data quality report (Part 1)", "",
           "Generated by `data_pipeline/data_report.py`. Each check compares our data with an independent "
           "real reference. Numbers behind every chart are in the table under it.", ""]

    # 1. calibration: synthetic gas & electricity vs NEED medians + IQR
    for fuel, key, title in [("gas", "gas", "Annual gas, gas-heated homes"),
                             ("electricity", "elec", "Annual electricity, gas-heated homes")]:
        r = pd.read_csv(REPORTS / f"calibration_{fuel}.csv", index_col=0)
        r = r[r["n_sim"] >= 100]
        fig, ax = plt.subplots(figsize=(7.5, 0.32 * len(r) + 1.2))
        y = np.arange(len(r))
        for off, lo, mid, hi, col, lab in [(-0.17, r.sim_q25, r.sim_median, r.sim_q75, OURS, "Ours (synthetic)"),
                                           (0.17, r[f"{key}_q25"], r[f"{key}_median"], r[f"{key}_q75"], REF,
                                            "NEED 2024 (real)")]:
            ax.hlines(y + off, lo, hi, color=col, linewidth=2)
            ax.plot(mid, y + off, "o", color=col, markersize=6, label=lab, markeredgecolor=SURFACE, markeredgewidth=1)
        ax.set_yticks(y, [c.replace("|", " · ").replace("_", " ") for c in r.index])
        ax.invert_yaxis()
        ax.legend(frameon=False, fontsize=8, labelcolor=INK2, loc="lower right")
        style(ax, f"{title}: median and IQR", "kWh per year")
        ax.grid(axis="x", color=GRID)
        path = save(fig, f"calibration_{fuel}.png")
        err = (r.sim_median / r[f"{key}_median"] - 1).abs().max()
        iqr = ((r.sim_q75 - r.sim_q25) / (r[f"{key}_q75"] - r[f"{key}_q25"])).median()
        out += [f"## Calibration: {fuel}", "",
                f"Largest median error across cells: **{err:.1%}**. Our inter-quartile range is "
                f"**{iqr:.0%}** of NEED's (median across cells): synthetic homes are a little more alike than "
                "real ones.", "", f"![]({path})", "",
                md_table(r[["sim_median", f"{key}_median", "sim_q25", f"{key}_q25", "sim_q75", f"{key}_q75",
                            "n_sim"]].round(0)), ""]

    # 2. performance-gap shape: gas per m2 by EPC band (houses, gas boilers) vs NEED Table 14.2
    props = pd.read_parquet(PROCESSED / "properties.parquet")
    true = pd.read_parquet(PROCESSED / "labels" / "true_annual_energy.parquet")
    t = props.merge(true, on="property_id")
    houses = t[t["property_type"].isin(["detached", "semi_detached", "terraced", "bungalow"])
               & t["heating_system"].isin(["gas_boiler_condensing", "gas_boiler_old"])]
    ours = (houses["true_annual_gas_kwh"] / houses["floor_area_m2"]).groupby(houses["energy_rating"]).median()
    h = pd.read_parquet(PROCESSED / "reference" / "need_headline.parquet")
    need = h[(h.fuel == "gas_per_m2") & (h.dimension == "epc_band") & (h.metric == "median")
             & (h.year == h.year.max()) & h.category.isin(list("ABCDEFG"))].set_index("category")["value"]
    bands = [b for b in "ABCDEFG" if b in ours.index]
    rel_ours, rel_need = ours / ours["D"], need / need["D"]
    fig, ax = plt.subplots(figsize=(7.5, 3.4))
    x = np.arange(len(bands))
    ax.bar(x - 0.2, rel_ours.reindex(bands), width=0.38, color=OURS, label="Ours (synthetic)", edgecolor=SURFACE)
    ax.bar(x + 0.2, rel_need.reindex(bands), width=0.38, color=REF, label="NEED 2024 (real)", edgecolor=SURFACE)
    ax.axhline(1.0, color=INK2, linewidth=0.8)
    ax.set_xticks(x, bands)
    ax.set_ylim(0, 1.3)
    ax.legend(frameon=False, fontsize=8, labelcolor=INK2, loc="upper left", ncol=2)
    style(ax, "Gas use per m² by EPC band, relative to band D (gas-heated houses)", "EPC band",
          "relative to band D")
    path = save(fig, "gas_per_m2_by_band.png")
    n_band = houses["energy_rating"].value_counts()
    tab = pd.DataFrame({"ours kWh/m²": ours.reindex(bands), "NEED kWh/m²": need.reindex(bands),
                        "ours vs D": rel_ours.reindex(bands), "NEED vs D": rel_need.reindex(bands),
                        "homes (ours)": n_band.reindex(bands)}).round(3)
    out += ["## Performance gap: gas per m² by EPC band", "",
            "Real homes (NEED) show a much flatter gradient across EPC bands than the ratings imply: F/G homes "
            "use no more gas per m² than D/E homes (the *prebound effect*: occupants of poorly rated homes heat "
            "less, and RdSAP overstates old-fabric heat loss). Without correction our physics model made F/G homes "
            "~40-55% too hungry, which would overstate their retrofit savings. A per-band behaviour factor, fitted "
            "jointly with the type x age calibration, reproduces NEED's relative curve (chart). Absolute levels "
            "differ by ~15% because NEED's band table (houses, all tariffs) and its type x age table (standard "
            "tariff, used for the level) cover different populations. Band G has too few homes to fit and borrows "
            "band F's factor.", "", f"![]({path})", "", md_table(tab), ""]

    # 3. EPC band mix vs NEED national
    nb = h[(h.source.str.endswith("Table_27")) & (h.metric == "count") & (h.year == h.year.max())
           & h.category.isin(list("ABCDEFG"))].set_index("category")["value"]
    mix = pd.DataFrame({"ours": props["energy_rating"].value_counts(normalize=True),
                        "England & Wales (NEED)": nb / nb.sum()}).reindex(list("ABCDEFG")) * 100
    fig, ax = plt.subplots(figsize=(7.5, 3.2))
    x = np.arange(7)
    ax.bar(x - 0.2, mix["ours"], width=0.38, color=OURS, label="Our product sample", edgecolor=SURFACE)
    ax.bar(x + 0.2, mix["England & Wales (NEED)"], width=0.38, color=REF, label="England & Wales (NEED 2024)",
           edgecolor=SURFACE)
    ax.set_xticks(x, list("ABCDEFG"))
    ax.legend(frameon=False, fontsize=8, labelcolor=INK2)
    style(ax, "EPC band mix", "EPC band", "% of homes")
    path = save(fig, "band_mix.png")
    out += ["## Representativeness: EPC band mix", "", f"![]({path})", "", md_table(mix.round(1)), ""]

    # 4. parse coverage (single series)
    cov = pd.read_csv(REPORTS / "epc_parse_coverage.csv", index_col=0)["coverage"].sort_values()
    fig, ax = plt.subplots(figsize=(7.5, 3.4))
    ax.barh(cov.index.str.replace("_", " "), cov * 100, color=OURS, height=0.6, edgecolor=SURFACE)
    for i, v in enumerate(cov * 100):
        ax.text(v - 1, i, f"{v:.1f}%", va="center", ha="right", color=SURFACE, fontsize=8)
    ax.set_xlim(0, 100)
    style(ax, "EPC text → enum coverage (2.9M certificates)", "% of certificates mapped")
    ax.grid(axis="x", color=GRID)
    path = save(fig, "parse_coverage.png")
    out += ["## EPC parsing coverage", "",
            "Unmapped values stay unknown (never guessed). Wall type and renewables gaps are new-build "
            "U-value-only and pre-2012 certificates; heating gaps are mostly community schemes (out of scope).",
            "", f"![]({path})", "", md_table((cov * 100).round(2).to_frame("coverage %")), ""]

    # 5. real retrofit evidence from repeat EPCs
    rh = pd.read_csv(REPORTS / "retrofit_history_summary.csv", index_col=0)
    rh = rh.sort_values("single_change_median_delta_sap")
    fig, ax = plt.subplots(figsize=(7.5, 3.2))
    ax.barh(rh.index.str.replace("_", " "), rh["single_change_median_delta_sap"], color=OURS, height=0.6,
            edgecolor=SURFACE)
    for i, v in enumerate(rh["single_change_median_delta_sap"]):
        ax.text(v + 0.2, i, f"+{v:.0f}", va="center", color=INK2, fontsize=8)
    style(ax, "Observed SAP gain, single-change repeat EPCs", "median SAP points")
    ax.grid(axis="x", color=GRID)
    path = save(fig, "retrofit_delta_sap.png")
    out += ["## Real retrofit evidence (repeat EPCs)", "",
            "Pairs where two or more elements got worse (assessor inconsistency) or floor area changed by over 15% "
            "were discarded.", "", f"![]({path})", "", md_table(rh.round(2)), ""]

    # 6. sales + recommender label summaries
    out += ["## Land Registry join", "", md_table(pd.read_csv(REPORTS / "ppd_match_report.csv", index_col=0)), "",
            "## Recommender labels vs feasibility rules", "",
            "When our rules call a retrofit infeasible, assessors almost never recommend it "
            "(`recommended_when_rule_infeasible`), so the rules agree with real assessors.", "",
            md_table(pd.read_csv(REPORTS / "recommender_label_rates.csv", index_col=0)), ""]
    (REPORTS / "data_report.md").write_text("\n".join(out))
    print("wrote reports/data_report.md and", len(list(FIG.glob("*.png"))), "figures")
    print(tab.to_string())


if __name__ == "__main__":
    main()
