"""Build reports/evaluation.md (submission item G) from saved metrics and model manifests.

Every number comes from files written by the training scripts, so the report is reproducible:
    python -m training.evaluation_report
"""

from __future__ import annotations

import json

import pandas as pd

from training.common import MODELS, REPORTS


def man(name: str) -> dict:
    return json.loads((MODELS / name / "manifest.json").read_text())


def table(df: pd.DataFrame, digits: int = 3) -> str:
    return df.round(digits).to_markdown()


def ci(m: dict, key: str = "mae_ci95", fmt: str = "{:.2f}") -> str:
    lo, hi = m[key]
    return f"{fmt.format(lo)}-{fmt.format(hi)}"


def main() -> None:
    out = [
        "# Evaluation report (Part 3 models)",
        "",
        "Generated by `training/evaluation_report.py` from `models/*/manifest.json` and `reports/*.csv`.",
        "",
        "## Methodology common to all models",
        "",
        "- **Splits**: one file, `data/processed/splits.parquet`, assigns every one of 1.84M properties to "
        "train/val/test (70/15/15) **by synthetic customer**, so no property or customer appears in two "
        "splits. "
        "Historic certificates and sales inherit their property's split.",
        "- **Train** fits the model; **val** is used for early stopping and threshold tuning only; "
        "**test** is "
        "reported and never used for any choice.",
        "- **Uncertainty**: 95% CIs are bootstraps over *properties* (all rows of a property resampled "
        "together), "
        "200 resamples.",
        "- **Features**: `greenhome/ml/features.py`, the same builder at training and inference; only "
        "fields the "
        "app receives (HomeInput) are used. Hidden simulator factors are never features.",
        "- **Baselines**: every model is compared with simple baselines on the same rows.",
        "- **Determinism**: LightGBM seed 42, deterministic mode.",
        "",
    ]

    # sizes
    sizes = pd.read_csv(REPORTS / "model_sizes.csv", index_col=0)
    out += ["## Models at a glance", "", table(sizes, 2), ""]

    # M4 rating
    r = man("rating")["metrics"]
    rows = {}
    for split in ("val", "test"):
        for k, label in (
            ("model", "model"),
            ("baseline_median_by_age_type", "baseline: median SAP by age x type"),
        ):
            m = r[split][k]
            rows[(split, label)] = {
                "MAE (SAP pts)": m["mae"],
                "MAE 95% CI": ci(m),
                "RMSE": m["rmse"],
                "R2": m["r2"],
                "band accuracy": m["band_accuracy"],
                "within one band": m["within_one_band"],
            }
    out += [
        "## M4: EPC rating (SAP points)",
        "",
        "Real EPC certificates; target SAP 1-100; monotone +1 on insulation, glazing, controls, renewables "
        "and "
        "heating-efficiency rank (a better state never lowers the predicted rating).",
        "",
        table(pd.DataFrame(rows).T),
        "",
        "**Retrofit gains vs real evidence.** Model-implied SAP gain on test homes where the retrofit is "
        "feasible, "
        "vs the median gain observed between repeat EPCs when only that element changed:",
        "",
        table(pd.read_csv(REPORTS / "rating_model_delta_sap.csv", index_col=0), 2),
        "",
        "Model gains are smaller than repeat-EPC gains for heat pumps and loft insulation. Real repeat "
        "pairs mix in "
        "concurrent renovations and EPC methodology changes (RdSAP 10 favours heat pumps), so they "
        "overstate the "
        "single-measure effect; the model estimates each measure with everything else held constant, which "
        "is "
        "the conservative input to the value estimate.",
        "",
    ]

    # M1 energy
    em = pd.read_csv(REPORTS / "energy_model_metrics.csv", index_col=[0, 1])
    e = man("energy_elec")["metrics"]
    out += [
        "## M1: post-retrofit energy per fuel",
        "",
        "Two regressors (electricity, gas) trained on simulator labels whose hidden household factors the "
        "model "
        "cannot see; each predicts the after/before ratio of its own fuel. Errors are on the **saving** "
        "(kWh/yr), "
        "the quantity the app reports.",
        "",
        table(em, 1),
        "",
        f"Test MAE on net saving, 95% CI: {ci(e['test']['model'], 'mae_saving_net_ci95', '{:.0f}')} kWh/yr.",
        "",
        "- **Interactions**: on packages of 2+ retrofits the model's error is far below adding "
        "single-retrofit "
        "savings (B3), i.e. package savings are not additive and the model captures that.",
        "- **Heat pump**: the electricity increase is predicted in the right direction "
        "(`elec_increase_sign_accuracy_hp`).",
        "",
        "**Performance gap check (real-world evidence).** Median gas saving for single loft / cavity "
        "insulation "
        "on test gas homes, vs savings actually observed in NEED:",
        "",
        table(pd.read_csv(REPORTS / "energy_performance_gap.csv", index_col=0), 1),
        "",
        "Engineering-based estimates exceed observed savings, most clearly for cavity wall insulation. The "
        "app "
        "labels all savings as estimates; this gap is stated as a limitation.",
        "",
    ]

    # M2 recommender
    rm = pd.read_csv(REPORTS / "recommender_metrics.csv", index_col=0)
    nd = pd.read_csv(REPORTS / "recommender_ndcg.csv", index_col=0).iloc[:, 0]
    out += [
        "## M2: retrofit relevance (real assessor recommendations)",
        "",
        "One binary classifier per retrofit, trained on rule-feasible certificates; label = the EPC assessor "
        "recommended it. Threshold tuned on val (max F1); metrics on test. Heat pump: trained and "
        "evaluated on "
        "2025+ certificates only, because earlier EPC software never recommended heat pumps.",
        "",
        table(
            rm[
                [
                    "positive_rate_test",
                    "roc_auc",
                    "popularity_auc",
                    "pr_auc",
                    "precision",
                    "recall",
                    "f1",
                    "recommend_all_f1",
                ]
            ]
        ),
        "",
        f"Ranking across retrofits per certificate (NDCG@3 vs the assessor's own order, test): model "
        f"{nd['model']:.3f}, popularity-by-type {nd['popularity_by_type']:.3f}, random "
        f"{nd['random_order']:.3f}. "
        "Assessors list measures in a fixed order by measure type, which type base rates capture almost "
        "exactly, "
        "so popularity wins on cross-retrofit ordering; the model's value is discriminating **which "
        "homes** need "
        "each measure (AUC). The app's final order comes from dependency rules + M1 savings + this "
        "probability.",
        "",
        "Solar, cavity and solid wall insulation are recommended in 95-97% of feasible cases, so their "
        "labels carry little information (F1 equals recommend-all).",
        "",
    ]

    # M3 value
    v = man("value")["metrics"]
    rows = {}
    for split in ("val", "test"):
        rows[(split, "model (ensemble median)")] = {
            "median APE %": v[split]["model"]["mape_pct"],
            "MAE GBP": v[split]["model"]["mae_gbp"],
        }
        rows[(split, "baseline: region x type GBP/m2, HPI-indexed")] = {
            "median APE %": v[split]["baseline_region_type_gbp_per_m2"]["mape_pct"],
            "MAE GBP": v[split]["baseline_region_type_gbp_per_m2"]["mae_gbp"],
        }
    out += [
        "## M3: property value and indicative uplift",
        "",
        "Hedonic model on real Land Registry sales with the EPC valid at sale; region-level location (what "
        "the "
        "app knows) and the regional HPI at the sale month; 20 property-bootstrap members; monotone +1 on "
        "rating. "
        "Uplift for a rating change = P10-P90 across members.",
        "",
        table(pd.DataFrame(rows).T, 1),
        "",
        "**Model-implied uplift at 2026-07, test homes (median of per-home P10 / median / P90):**",
        "",
        table(pd.read_csv(REPORTS / "value_uplift_summary.csv", index_col=[0, 1]), 2),
        "",
        "**Real-world check: repeat sales whose EPC band changed** (val+test properties; observed change is "
        "HPI-adjusted):",
        "",
        table(pd.read_csv(REPORTS / "value_repeat_sales_check.csv", index_col=0), 2),
        "",
        "**Transparency check: OLS hedonic premium vs band D** (controls: floor area, type, age, local "
        "authority x "
        "year; SEs clustered by property):",
        "",
        table(pd.read_csv(REPORTS / "value_ols_band_coefficients.csv", index_col=0), 2),
        "",
        "Associations, not causal effects: better-rated homes differ in unobserved condition and renovation "
        "quality. The app reports a range and labels it indicative.",
        "",
    ]

    out += [
        "## Limitations",
        "",
        "- M1 is trained on simulated outcomes calibrated to NEED; agreement with simulated targets does not "
        "prove real-world accuracy (see the performance-gap table).",
        "- M3 uses region-level location only, so absolute price error is large; the uplift ratio is what "
        "the "
        "app uses, applied to the user's own value.",
        "- M2 labels reflect assessor software rules as much as home need; heat-pump labels exist only "
        "from 2025.",
        "- City-heavy sample (11 local authorities); England and Wales only.",
        "",
    ]
    (REPORTS / "evaluation.md").write_text("\n".join(out))
    print("wrote reports/evaluation.md")


if __name__ == "__main__":
    main()
